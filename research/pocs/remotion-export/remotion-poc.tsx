import React from 'react';
import { AbsoluteFill, useVideoConfig, useCurrentFrame, Audio, Sequence } from 'remotion';

// Minimal Proof of Concept for generating video with Remotion
// This would be imported and rendered using @remotion/player in the client
// or rendered on the server using @remotion/lambda / @remotion/bundler

export const HighlightVideo: React.FC<{
  audioUrl: string;
  transcriptSegments: Array<{ text: string; start: number; end: number }>;
  themeColor: string;
}> = ({ audioUrl, transcriptSegments, themeColor }) => {
  const { fps } = useVideoConfig();
  const frame = useCurrentFrame();
  const currentTime = frame / fps;

  // Find the currently active subtitle
  const currentSegment = transcriptSegments.find(
    (seg) => currentTime >= seg.start && currentTime <= seg.end
  );

  return (
    <AbsoluteFill
      style={{
        backgroundColor: '#111',
        display: 'flex',
        justifyContent: 'center',
        alignItems: 'center',
        flexDirection: 'column',
      }}
    >
      <Audio src={audioUrl} />

      {/* Decorative Waveform Mockup */}
      <div
        style={{
          width: '60%',
          height: '150px',
          backgroundColor: themeColor,
          opacity: 0.2,
          borderRadius: '20px',
          marginBottom: '50px',
          display: 'flex',
          alignItems: 'center',
          justifyContent: 'center',
        }}
      >
        <div style={{ color: themeColor, fontSize: '30px' }}>
          [Dynamic Waveform Visualization]
        </div>
      </div>

      {/* Burned-in Dynamic Captions */}
      <div
        style={{
          fontSize: '60px',
          color: 'white',
          textAlign: 'center',
          fontFamily: 'sans-serif',
          fontWeight: 'bold',
          maxWidth: '80%',
          textShadow: `0 4px 8px rgba(0,0,0,0.5)`,
        }}
      >
        {currentSegment ? (
          <span style={{ color: themeColor }}>{currentSegment.text}</span>
        ) : (
          <span style={{ opacity: 0 }}>...</span>
        )}
      </div>

      <AbsoluteFill
        style={{
          justifyContent: 'flex-end',
          alignItems: 'center',
          paddingBottom: '40px',
        }}
      >
        <div style={{ color: 'rgba(255,255,255,0.5)', fontSize: '30px' }}>
          Generated by AudioHighlights
        </div>
      </AbsoluteFill>
    </AbsoluteFill>
  );
};

// Example Configuration for the Composition
export const RemotionComposition = () => {
  return (
    <Sequence from={0} durationInFrames={300}>
      <HighlightVideo
        audioUrl="mock_audio.mp3"
        transcriptSegments={[
          { text: "Welcome to this podcast.", start: 0, end: 2 },
          { text: "Today we are discussing AI.", start: 2.5, end: 5 },
          { text: "It's a fascinating topic.", start: 5.5, end: 8 },
        ]}
        themeColor="#ff4081"
      />
    </Sequence>
  );
};
